function rememberDefault(element, attr, storeAttr) {
  if (!element.hasAttribute(storeAttr)) {
    element.setAttribute(storeAttr, attr ? element.getAttribute(attr) || "" : element.innerHTML);
  }
}

function decodeHtmlEntities(value) {
  const textarea = document.createElement("textarea");
  let decoded = value || "";

  for (let i = 0; i < 3; i += 1) {
    textarea.innerHTML = decoded;
    if (textarea.value === decoded) break;
    decoded = textarea.value;
  }

  return decoded;
}

function translateElement(element, lang) {
  const htmlKey = element.dataset.i18nHtml;
  const textKey = element.dataset.i18n;

  if (htmlKey) {
    rememberDefault(element, null, "data-i18n-default-html");
    element.innerHTML = lang === "en" && I18N_EN[htmlKey]
      ? I18N_EN[htmlKey]
      : element.getAttribute("data-i18n-default-html");
    return;
  }

  if (textKey) {
    if (!element.hasAttribute("data-i18n-default-text")) {
      element.setAttribute("data-i18n-default-text", element.textContent);
    }
    element.textContent = lang === "en" && I18N_EN[textKey]
      ? I18N_EN[textKey]
      : decodeHtmlEntities(element.getAttribute("data-i18n-default-text"));
  }
}

function translateAttribute(element, dataKey, attr, defaultAttr, lang) {
  const key = element.dataset[dataKey];
  if (!key) return;

  rememberDefault(element, attr, defaultAttr);
  element.setAttribute(
    attr,
    lang === "en" && I18N_EN[key] ? I18N_EN[key] : element.getAttribute(defaultAttr)
  );
}

function applyLanguage(lang) {
  const nextLang = lang === "en" ? "en" : "ko";
  document.documentElement.lang = nextLang;
  localStorage.setItem("rexolution-lang", nextLang);

  document.querySelectorAll("[data-i18n], [data-i18n-html]").forEach((element) => {
    translateElement(element, nextLang);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    translateAttribute(element, "i18nPlaceholder", "placeholder", "data-i18n-default-placeholder", nextLang);
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    translateAttribute(element, "i18nTitle", "title", "data-i18n-default-title", nextLang);
  });

  document.querySelectorAll("[data-i18n-src]").forEach((element) => {
    translateAttribute(element, "i18nSrc", "src", "data-i18n-default-src", nextLang);
  });

  document.querySelectorAll(".language-current").forEach((button) => {
    button.textContent = nextLang === "en" ? "EN" : "KR";
  });

  document.querySelectorAll("[data-lang-option]").forEach((button) => {
    button.classList.toggle("active", button.dataset.langOption === nextLang);
  });

  const pageName = window.location.pathname.split("/").pop() || "index.html";
  if (I18N_TITLES[pageName]) {
    document.title = I18N_TITLES[pageName][nextLang];
  }

  window.dispatchEvent(new CustomEvent("rexolution:languagechange", {
    detail: { lang: nextLang }
  }));
}

window.getLangText = function getLangText(key, fallback) {
  return localStorage.getItem("rexolution-lang") === "en" && I18N_EN[key] ? I18N_EN[key] : fallback;
};

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("rexolution-lang") || "ko";

  document.querySelectorAll("[data-lang-option]").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.langOption));
  });

  applyLanguage(savedLang);
});
